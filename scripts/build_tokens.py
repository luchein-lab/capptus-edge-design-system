"""Generate portable CSS from the selected Mineral Bloom token source."""
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[1]


def render():
    data = json.loads((ROOT / 'tokens/mineral-bloom.json').read_text())
    lines = ['/* Generated by scripts/build_tokens.py. Edit mineral-bloom.json. */', ':root {']
    for name, entry in data['color'].items():
        lines.append(f'  --capptus-{name}: {entry["value"]};')
    for name, target in data['semantic'].items():
        if target not in data['color']:
            raise ValueError(f'Unknown colour alias: {name} = {target}')
        lines.append(f'  --capptus-{name}: var(--capptus-{target});')
    for name, entry in data['typography'].items():
        lines.append(f'  --capptus-font-{name}: "{entry["family"]}", {entry["fallback"]};')
        lines.append(f'  --capptus-weight-{name}: {entry["weight"]};')
    return '\n'.join(lines + ['}', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    destination = ROOT / 'tokens/mineral-bloom.css'
    expected = render()
    if args.check:
        if not destination.exists() or destination.read_text() != expected:
            raise SystemExit('FAIL: generated tokens are stale; run python3 scripts/build_tokens.py')
        print('PASS token source and generated CSS agree')
    else:
        destination.write_text(expected)
        print('Wrote tokens/mineral-bloom.css')
